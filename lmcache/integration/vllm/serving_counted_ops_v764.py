"""Load only the counted-read extension identified by cold-start build evidence."""

# Standard
import hashlib
import importlib
import importlib.util
import json
import os
from pathlib import Path
import sys
from threading import RLock
from types import ModuleType

MODULE_NAME = "tutti_device_count_v137"
SYMBOLS = (
    "tutti_read_indexed_device_count",
    "tutti_read_indexed_segments_device_count",
)
SOURCE_FILES = (
    "csrc/tutti_kv_ops.cu",
    "csrc/tutti_kv_ops.cuh",
    "device_count_bindings_v137.cpp",
)
LOAD_LOCK = RLock()


def verify_build_receipt(receipt_path: Path, source_root: Path) -> dict:
    """Verify binary and source digests without importing CUDA or executing code.

    Args:
        receipt_path: BUILD.json generated by build_native.py.
        source_root: Current submission's native source directory.
    Returns:
        Validated build evidence with an absolute module path.
    Raises:
        ValueError: Missing, changed, incomplete or relocated binary/source data.
        OSError: A required file cannot be read.
    """
    receipt = json.loads(receipt_path.read_text())
    module = Path(receipt["module"])
    if not module.is_absolute() or module.suffix not in (".so", ".pyd"):
        raise ValueError("Build receipt must identify an absolute native module")
    if hashlib.sha256(module.read_bytes()).hexdigest() != receipt["module_sha256"]:
        raise ValueError("Native module differs from cold-start build")
    sources = receipt["identity"]["sources"]
    if set(sources) != set(SOURCE_FILES) or set(receipt["symbols"]) != set(SYMBOLS):
        raise ValueError("Incomplete counted-read build identity")
    for relative, digest in sources.items():
        if hashlib.sha256((source_root / relative).read_bytes()).hexdigest() != digest:
            raise ValueError(f"Native source changed since build: {relative}")
    return receipt


def load_counted_extension(receipt_path: Path, source_root: Path) -> ModuleType:
    """Load a verified, already-built module; never compile on a request path.

    Raises ValueError for source/binary or active module identity mismatch,
    RuntimeError for a different PyTorch/Python build, and ImportError for missing
    symbols. Requires the same source mount and receipt paths in every worker.
    """
    with LOAD_LOCK:
        receipt = verify_build_receipt(receipt_path, source_root)
        torch = importlib.import_module("torch")
        identity = receipt["identity"]
        if (
            identity["torch"] != torch.__version__
            or identity["torch_cuda"] != torch.version.cuda
            or identity["python"].split(".")[:2]
            != [str(sys.version_info.major), str(sys.version_info.minor)]
        ):
            raise RuntimeError("Worker toolchain differs from native build")
        path = Path(receipt["module"]).resolve()
        module = sys.modules.get(MODULE_NAME)
        if module is not None:
            if Path(module.__file__).resolve() != path:
                raise ValueError("Another counted-read extension is already loaded")
        else:
            spec = importlib.util.spec_from_file_location(MODULE_NAME, path)
            if spec is None or spec.loader is None:
                raise ImportError("Cannot load compiled counted-read extension")
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            sys.modules[MODULE_NAME] = module
        if any(not callable(getattr(module, symbol, None)) for symbol in SYMBOLS):
            raise ImportError("Counted-read extension lacks required symbols")
        return module


def ensure_counted_ops() -> None:
    """Install verified counted-read symbols through the canonical public c_ops.

    JANUS_COUNTED_BUILD_RECEIPT and JANUS_COUNTED_SOURCE_ROOT are mandatory.
    Missing configuration fails startup rather than loading a historical .so.
    This replaces the historical serving_counted_ops_v764 startup helper.
    """
    required = ("JANUS_COUNTED_BUILD_RECEIPT", "JANUS_COUNTED_SOURCE_ROOT")
    if any(not os.environ.get(name) for name in required):
        raise RuntimeError("Configure counted-read build receipt and source root")
    module = load_counted_extension(*(Path(os.environ[name]) for name in required))
    ops = importlib.import_module("lmcache.c_ops")
    package = importlib.import_module("lmcache")
    if getattr(package, "c_ops", None) is not ops:
        raise RuntimeError("LMCache c_ops alias is inconsistent")
    for symbol in SYMBOLS:
        setattr(ops, symbol, getattr(module, symbol))
    os.environ["JANUS_LOADED_COUNTED_SHA256"] = hashlib.sha256(
        Path(module.__file__).read_bytes()
    ).hexdigest()


if __name__ == "__main__":
    extension = load_counted_extension(
        Path(os.environ["JANUS_COUNTED_BUILD_RECEIPT"]),
        Path(os.environ["JANUS_COUNTED_SOURCE_ROOT"]),
    )
    print(
        json.dumps(
            dict(
                module=extension.__file__,
                symbols=list(SYMBOLS),
                compiled_during_load=False,
            )
        )
    )
