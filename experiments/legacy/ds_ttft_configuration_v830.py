"""Explicit DS performance controls, separate from GLM prediction hooks."""


def environment(arm: str) -> dict[str, str]:
    """Return DS-only controls with full-query local K sharding for the K arm."""
    if arm not in ("k_local", "no_prefetch", "ssd_only"):
        raise ValueError("unsupported DS arm")
    flags = dict(
        LMCACHE_DS_TTFT_EXPERIMENT_V830="1", LMCACHE_DS_TTFT_ARM=arm,
        LMCACHE_CSA_PREFETCH_CP_MODE="key_sharded_owner",
        LMCACHE_CSA_PREFETCH_CP_SIZE="8", LMCACHE_CSA_PREFETCH_CP_INTERLEAVE="64",
        LMCACHE_CSA_PREFETCH_CP_EXCHANGE_IDS="0",
        LMCACHE_CSA_PREFETCH_CP_QUERY_SAMPLE_STRIDE="1",
        LMCACHE_CSA_PREFETCH_MIN_HISTORY_BLOCKS="0",
        LMCACHE_CSA_PREDICTION_DENSIFY_PERCENT="0",
        LMCACHE_CSA_PROPAGATE_TOPK_LAYERS="0", LMCACHE_CSA_PREFETCH_CP_OVERSUBSCRIBE="1",
        LMCACHE_CSA_PREFETCH_LOOKAHEAD_BY_LAYER="default:2",
        LMCACHE_CSA_OWNER_BLOCKS_PER_RANK="512",
        LMCACHE_CSA_PROXY_QUERY_TILE_ROWS="2048", LMCACHE_CSA_PROXY_KEY_BUCKET="1",
        LMCACHE_SSD_TP_GATHER_MAX_CTAS="2", LMCACHE_SSD_TP_GATHER_MAX_NCHANNELS="0",
        LMCACHE_PROXY_INDEXER_CP="0", LMCACHE_PROXY_INDEXER_K_CP="0",
        LMCACHE_TRUE_INDEXER_CP="0", LMCACHE_GLM_DSA_LAYER_MAJOR="0",
        LMCACHE_GLM_DSA_PREDICTIVE_PREFETCH="0",
        LMCACHE_DSV4_OWNER_BACKGROUND_LAUNCH="0", LMCACHE_CSA_PREFETCH_EXACT_K_SYNC="0",
        LMCACHE_DSV4_CONTINUATION_CORRECTION="1",
        LMCACHE_DSV4_FINAL_STORE_BOUNDARY_V737="1",
        LMCACHE_DSV4_CPU_RAW_WRITE="1", LMCACHE_TUTTI_CPU_STAGE_ENABLE="1",
        LMCACHE_TUTTI_CPU_STAGE_GIB="2", LMCACHE_TUTTI_PAUSE_WRITES_DURING_DECODE="1",
        LMCACHE_TUTTI_UNLIMITED_WRITES_DURING_DECODE="0",
        LMCACHE_TUTTI_DECODE_WRITE_MIBPS="0")
    for key in ("LMCACHE_INDEXER_PROFILE_ACCURACY", "LMCACHE_INDEXER_TIMING",
                "LMCACHE_CSA_ATTENTION_KV_TIMING", "LMCACHE_TTFT_STAGE_PROFILE",
                "LMCACHE_D2H_TIMING", "LMCACHE_HCA_TIMING", "LMCACHE_TUTTI_PROFILE",
                "LMCACHE_TUTTI_DEVICE_TIMESTAMPS", "LMCACHE_TUTTI_COUNTED_VOLUME_PROFILE",
                "LMCACHE_DS_IO_VOLUME_PROFILE", "LMCACHE_DS_COMPLETE_IO_V510",
                "LMCACHE_DS_TIMELINE_V518", "LMCACHE_DS_EXACT_SET_EXPORT",
                "LMCACHE_DS_KINETO_V551", "LMCACHE_DS_MODEL_STAGES_V558",
                "LMCACHE_CSA_DECODE_SSD_PROFILE", "LMCACHE_CSA_PIPELINE_NVTX",
                "LMCACHE_EXPERIMENT_NVTX", "LMCACHE_CSA_DETAILED_IO_NVTX",
                "LMCACHE_NSYS_CAPTURE", "LMCACHE_NSYS_FULL_CAPTURE",
                "LMCACHE_EXPERIMENT_DS_FORWARD_AUDIT_V382"):
        flags[key] = "0"
    return flags
